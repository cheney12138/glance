/// 唤起落点的规则(2026-09-14,第三版)。
///
/// 这条规则被写错过两次,两次都是"看起来修好了"的那种错。把三段历史钉在这里,免得再来第三次:
///
/// | 版本 | 做法 | 观感 | 环序 |
/// |---|---|---|---|
/// | v1 | `swapAt(0, 1)` 把上一个 App 换到第一格,高亮落第一格 | 对 | **错**:当前 App 停在第二格,按一发 Tab 又回到自己 |
/// | v2 | 左旋一格(当前 App 沉队尾),高亮落第一格 | **错**:第一格不再是当前 App,与原生第一眼不符 | 对 |
/// | v3 | **什么都不做**,用 MRU 原序,高亮落**第二格** | 对:第一格 = 当前 App(原生如此) | 对:从第二格往后走,当前 App 最后才出现 |
///
/// 关键认识:**"第一眼的样子"与"环怎么走"是两件事**,而它们同时成立并不需要任何重排 ——
/// 输入本来就是 `[当前 App, 上一个 App, 更早的…, 最久没用的]`,于是:
///
/// ```
/// 第一格 = 当前 App(它在,但没被选中)   ← 高亮在第一格 = 选中自己,所以落点必须是第二格
/// 第二格 = 上一个 App                    ← ⌘Tab 一按就切到这里 = "唤起即切换"
/// 往后   = 更早的… → 最久没用的 → 绕回第一格(当前 App 最后才出现)
/// ```
///
/// 普通取模 `(i + 1) % count` 天然给出这条环;`⇧Tab` 往回一格则直接回到当前 App。
/// 前两版都是为了"让高亮落在第一格"去动顺序 —— 顺序一动,第一眼的版式就跟着错。
public enum LandingRule {
    /// 落点下标。**正向 = 第二格**(上一个 App);**反向 = 末格**(最久没用的那个)。
    ///
    /// 为什么正向不是 0:第一格是**当前 App** —— 落在那里等于"选中自己",
    /// 用户按一次 ⌘Tab 什么都没换,会被读成"这个开关没生效"(实评原文)。
    public static func landingIndex(count: Int, reverse: Bool) -> Int {
        guard count > 1 else { return 0 }
        return reverse ? count - 1 : 1
    }
}
